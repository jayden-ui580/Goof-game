"""Writes src/ServerScriptService/OozaruRig.luau from tools/rig/oozaru.json (made by
build_oozaru.py): where every bone of the Great Ape sits as designed (Roblox axes: x right,
y up, -z forward; feet on y = 0; the model's own units), so the server can measure how the
imported model came in (its size and turn) and fit it.
usage (from the DragonWish folder): python3 tools/rig/emit_oozaru.py"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
info = json.load(open(os.path.join(here, 'oozaru.json')))
bones = info['bones']
lo, hi = info['bounds']
out = []
out.append('-- GENERATED by tools/rig/emit_oozaru.py from tools/rig/oozaru.json: do not edit by hand.')
out.append('-- The Great Ape as designed: every bone\'s head (Roblox axes: x right, y up, -z forward, the')
out.append('-- feet standing on y = 0) in the model\'s own units, its size, and the meshes it is made of.')
out.append('return {')
out.append('\tSignatureBone = "TAIL18", -- (no other piece has a bone with this name)')
out.append('\tBounds = { Vector3.new(%.4f, %.4f, %.4f), Vector3.new(%.4f, %.4f, %.4f) },' % (*lo, *hi))
out.append('\tMeshes = { %s },' % ', '.join('"%s"' % m for m in info['meshes']))
out.append('\tBones = {')
for b in bones:
    h = b['head']
    out.append('\t\t%s = Vector3.new(%.4f, %.4f, %.4f),' % (b['name'], h[0], h[1], h[2]))
out.append('\t},')
out.append('}')
path = os.path.join(here, '..', '..', 'src', 'ServerScriptService', 'OozaruRig.luau')
open(path, 'w').write('\n'.join(out) + '\n')
print('wrote', os.path.normpath(path), len(bones), 'bones')
